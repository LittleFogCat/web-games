  function w(groups, hpMul) {
    return {
      groups: groups.map(function (group) {
        return { type: group[0], count: group[1], gap: group[2] };
      }),
      hpMul: hpMul || 1,
    };
  }

  function cloneWaveGroups(wave, countScale) {
    return wave.groups.map(function (group) {
      const count = group.type === 'boss'
        ? 1
        : Math.max(1, Math.round(group.count * countScale));
      return { type: group.type, count: count, gap: group.gap };
    });
  }

  function extendCampaign(level) {
    const base = level.waves.map(function (wave) {
      return {
        groups: cloneWaveGroups(wave, WAVE_POPULATION_SCALE),
        hpMul: wave.hpMul || 1,
      };
    });
    if (EXTRA_WAVES_PER_LEVEL <= 0 || base.length < 2) {
      level.waves = base;
      return;
    }
    const finalWave = base[base.length - 1];
    const preFinal = base.slice(0, -1);
    // Draw reinforcements from the middle of the route, not the hardest late waves.
    const poolStart = Math.floor(preFinal.length * 0.35);
    const poolEnd = Math.max(poolStart + 1, Math.floor(preFinal.length * 0.78));
    const pool = preFinal.slice(Math.max(0, poolStart), Math.min(preFinal.length, poolEnd));
    const extras = [];
    for (let i = 0; i < EXTRA_WAVES_PER_LEVEL; i++) {
      const progress = EXTRA_WAVES_PER_LEVEL === 1 ? 0.5 : i / (EXTRA_WAVES_PER_LEVEL - 1);
      const src = pool[Math.min(pool.length - 1, Math.floor(progress * (pool.length - 1)))];
      extras.push({
        groups: src.groups.map(function (group) {
          return {
            type: group.type,
            count: Math.max(1, Math.round(group.count * EXTRA_WAVE_POPULATION_SCALE)),
            gap: group.gap,
          };
        }),
        hpMul: 0.95 + i * 0.035,
      });
    }
    level.waves = preFinal.concat(extras, [finalWave]);
  }

  LEVELS.forEach(extendCampaign);

  function parseLevel(level) {
    const cells = [];
    const rocks = [];
    const gates = [];
    let base = null;
    for (let y = 0; y < GRID.rows; y++) {
      const row = level.map[y] || '';
      for (let x = 0; x < GRID.cols; x++) {
        const ch = row[x] || '.';
        const cell = { x: x, y: y, ch: ch };
        cells.push(cell);
        if (ch === '#') rocks.push(cell);
        if (ch === 'S') gates.push({ x: x, y: y });
        if (ch === 'B') base = { x: x, y: y };
      }
    }
    if (!base) base = { x: 4, y: 15 };
    if (!gates.length) gates.push({ x: 4, y: 0 });
    return { cells: cells, rocks: rocks, gates: gates, base: base };
  }

